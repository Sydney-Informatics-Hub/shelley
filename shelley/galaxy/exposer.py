"""Makes a Galaxy SIF loadable as a shared Lmod module, else remove artefacts
on cancellation or failure.

A build is split in two:

- ``plan`` gathers everything that can fail for reasons outside shelley's control (the
  upstream registry over the network, alias discovery, the ``-i`` prompt) and writes
  nothing. Cancelling a prompt or losing the network here leaves ``/apps`` untouched.
- ``apply`` performs the writes inside a ``BuildTransaction``. Rebuilding an installed
  tag first moves the existing install aside, so a failure restores it exactly.

On-disk results are the same as 0.4.0's (shpc layout, Lmod link, registry entry and
marker formats), except the local tag value, which is now ``local:keep-path`` instead
of a hash of the whole SIF.
"""

import shutil
from collections.abc import Callable
from pathlib import Path

from ..builder.guts_integration import normalize_aliases
from ..results import BuildPlan
from ..tags import Tag
from ..tools.lmod import Lmod
from ..tools.shpc import Shpc
from ..transaction import BuildTransaction
from ..utils import globals as gl
from ..utils.perms import ensure_traversable, harden_tree
from .aliases import discover_aliases
from .registry import (
    LOCAL_TAG_VALUE,
    LocalRegistry,
    Marker,
    RegistryClient,
    merged_with_upstream,
)

URI_PREFIX = "quay.io/biocontainers"

Curate = Callable[[list[dict]], list[dict]]


class ShpcExposer:
    def __init__(
        self,
        registry: RegistryClient | None = None,
        local: LocalRegistry | None = None,
        shpc: Shpc | None = None,
        lmod: Lmod | None = None,
        discover: Callable[..., list[dict]] = discover_aliases,
    ):
        self.registry = registry or RegistryClient()
        self.local = local or LocalRegistry()
        self.shpc = shpc or Shpc()
        self.lmod = lmod or Lmod()
        self.discover = discover

    @staticmethod
    def uri(tool: str) -> str:
        return f"{URI_PREFIX}/{tool}"

    def tool_dirs(self, tool: str) -> list[Path]:
        """The tool's directories: every path a build of ``tool`` may create or change.

        One each under shpc's modules, wrappers and containers, the local registry entry,
        and the Lmod modulefile directory. See the glossary, "Tool directories".
        """
        uri = self.uri(tool)
        return [
            gl.shpc_module_base() / uri,
            gl.shpc_wrapper_base() / uri,
            gl.shpc_container_base() / uri,
            self.local.entry_dir(uri),
            self.lmod.modules_dir / tool,
        ]

    def _tag_paths(self, tool: str, tag: Tag) -> list[Path]:
        uri = self.uri(tool)
        return [
            gl.shpc_module_base() / uri / tag.raw,
            gl.shpc_wrapper_base() / uri / tag.raw,
            gl.shpc_container_base() / uri / tag.raw,
            self.lmod.link_path(tool, tag),
        ]

    # ------------------------------------------------------------------ plan
    def plan(
        self, tool: str, tag: Tag, sif: Path, curate: Curate | None = None
    ) -> BuildPlan:
        """Decide every write of the build. Writes nothing.

        Raises ``NetworkUnavailable`` (registry or alias discovery unreachable) and
        whatever ``curate`` raises when the user cancels.
        """
        uri = self.uri(tool)
        upstream = self.registry.fetch(uri)
        in_upstream = bool(upstream) and tag.raw in ((upstream or {}).get("tags") or {})

        local = self.local.read(uri)
        remove_legacy = local is not None and self.local.is_legacy(
            uri, self.lmod.linked_tags(tool)
        )
        if remove_legacy:
            local = None

        local_entry: dict | None = None
        marker: Marker | None = None
        if not in_upstream or curate is not None:
            # A local entry for this tag: absent upstream, or aliases curated with -i.
            if in_upstream:
                aliases = normalize_aliases((upstream or {}).get("aliases") or [])
            else:
                aliases = self.discover(sif, keep=tool)
            if curate is not None:
                aliases = curate(aliases)
            entry = merged_with_upstream(local or upstream or {"docker": uri}, upstream)
            entry["tags"][tag.raw] = LOCAL_TAG_VALUE
            entry["aliases"] = aliases
            # shpc's schema requires these on every container.yaml.
            if not entry.get("latest"):
                entry["latest"] = {tag.raw: LOCAL_TAG_VALUE}
            entry.setdefault(
                "maintainer",
                "Auto-generated by Shelley (BioShell); not yet curated in the "
                "upstream singularityhub/shpc-registry.",
            )
            entry.setdefault(
                "description",
                f"{uri} — registered locally by Shelley because it is not "
                "(yet) present in the upstream singularityhub/shpc-registry.",
            )
            local_entry, marker = entry, Marker(tag.raw, aliases, in_upstream)
        elif local is not None:
            # shpc stops at the first registry with this name, so refresh the local
            # entry with upstream's tags or it would hide this one.
            aliases = normalize_aliases(local.get("aliases") or [])
            local_entry = merged_with_upstream(local, upstream)
        else:
            aliases = normalize_aliases((upstream or {}).get("aliases") or [])

        replace_existing = any(
            p.exists() or p.is_symlink() for p in self._tag_paths(tool, tag)
        )
        return BuildPlan(
            tool=tool,
            tag=tag,
            uri=uri,
            sif=sif,
            in_upstream=in_upstream,
            aliases=aliases,
            local_entry=local_entry,
            marker=marker,
            remove_legacy=remove_legacy,
            replace_existing=replace_existing,
        )

    # ------------------------------------------------------------------ apply
    def apply(self, plan: BuildPlan) -> Path:
        """Perform the planned writes atomically; return the modulefile link."""
        with BuildTransaction(plan.tool, self.tool_dirs(plan.tool)) as tx:
            if plan.replace_existing:
                self._move_aside(plan, tx)
            if plan.remove_legacy:
                shutil.rmtree(self.local.entry_dir(plan.uri))
            if plan.local_entry is not None:
                self.local.write(plan.uri, plan.local_entry, plan.marker)
            self.shpc.install(f"{plan.uri}:{plan.tag.raw}", plan.sif)
            module_base = gl.shpc_module_base()
            self._harden(plan)
            link = self.lmod.link(
                plan.tool,
                plan.tag,
                module_base / plan.uri / plan.tag.raw / "module.lua",
            )
            tx.commit()
        return link

    def _move_aside(self, plan: BuildPlan, tx: BuildTransaction) -> None:
        for path in self._tag_paths(plan.tool, plan.tag):
            if path.exists() or path.is_symlink():
                aside = path.with_name(path.name + ".aside")
                path.rename(aside)
                tx.on_commit(lambda aside=aside: _remove(aside))

    def _harden(self, plan: BuildPlan) -> None:
        """World-readable and traversable, scoped to this tool (as in 0.4.0)."""
        for tool_dir in (
            gl.shpc_module_base() / plan.uri,
            gl.shpc_wrapper_base() / plan.uri,
            gl.shpc_container_base() / plan.uri,
            self.local.entry_dir(plan.uri),
        ):
            ensure_traversable(tool_dir)
            harden_tree(tool_dir)


def _remove(path: Path) -> None:
    if path.is_dir() and not path.is_symlink():
        shutil.rmtree(path)
    elif path.exists() or path.is_symlink():
        path.unlink()
